import { randomBytes } from 'node:crypto';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { config } from './config.js';

// The database: SQLite on this computer and in tests (DB_PATH), PostgreSQL online (DB_ENGINE=postgres with
// DATABASE_URL, e.g. a free Neon database). Both are used through the same small set of functions, all async:
//   one(sql, ...params)    the first row or undefined
//   all(sql, ...params)    every row
//   run(sql, ...params)    { changes } for UPDATE / DELETE
//   insert(sql, ...params) the new row's id
//   transaction(async (tx) => ...)  the same four on tx, all or nothing
// SQL is written with ? placeholders and SQL that both understand.

export const EXPENSE_CATEGORIES = ['seed', 'fertilizer', 'chemicals', 'labour', 'land', 'equipment', 'transport', 'water', 'other'];
export const TASK_KINDS = ['prepare', 'nursery', 'plant', 'weed', 'fertilize', 'scout', 'spray', 'water', 'harvest', 'other'];
const list = (values) => values.map((v) => `'${v}'`).join(', ');

export const engine = config.dbEngine === 'postgres' ? 'postgres' : 'sqlite';
const pg = engine === 'postgres';

// ISO-8601 UTC with milliseconds, same format as Date#toISOString(), so text comparison works.
export const NOW = pg ? `to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')` : "strftime('%Y-%m-%dT%H:%M:%fZ','now')";
const ID = pg ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
const REF = pg ? 'BIGINT' : 'INTEGER';
const REAL = pg ? 'DOUBLE PRECISION' : 'REAL';

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id            ${ID},
  name          TEXT NOT NULL,
  phone         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  county        TEXT,                -- one of the 47 counties (catalog/counties.js); sets the weather location
  latitude      ${REAL},             -- from the GPS when the farmer shares it, else the county's centre
  longitude     ${REAL},
  created_at    TEXT NOT NULL DEFAULT (${NOW})
);

-- A plot (shamba) planted with one crop for one season. Harvested plots stay for the records.
CREATE TABLE IF NOT EXISTS plots (
  id          ${ID},
  user_id     ${REF} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  crop        TEXT NOT NULL,          -- crop key from catalog/crops.js
  variety     TEXT,
  size_acres  ${REAL},
  planted_on  TEXT NOT NULL,          -- YYYY-MM-DD (transplanting date for crops raised in a nursery)
  status      TEXT NOT NULL DEFAULT 'growing' CHECK (status IN ('growing', 'harvested')),
  notes       TEXT,
  created_at  TEXT NOT NULL DEFAULT (${NOW})
);
CREATE INDEX IF NOT EXISTS idx_plots_user ON plots(user_id, status);

-- Farm activities: made from the crop calendar when a plot is added (source 'calendar'), or added by the farmer.
CREATE TABLE IF NOT EXISTS tasks (
  id         ${ID},
  user_id    ${REF} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plot_id    ${REF} REFERENCES plots(id) ON DELETE CASCADE,
  kind       TEXT NOT NULL DEFAULT 'other' CHECK (kind IN (${list(TASK_KINDS)})),
  title      TEXT NOT NULL,
  title_sw   TEXT,
  details    TEXT,
  details_sw TEXT,
  due_on     TEXT NOT NULL,
  done_at    TEXT,
  source     TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('calendar', 'manual')),
  created_at TEXT NOT NULL DEFAULT (${NOW})
);
CREATE INDEX IF NOT EXISTS idx_tasks_user_due ON tasks(user_id, done_at, due_on);

-- Money spent, in whole shillings.
CREATE TABLE IF NOT EXISTS expenses (
  id         ${ID},
  user_id    ${REF} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plot_id    ${REF} REFERENCES plots(id) ON DELETE SET NULL,
  category   TEXT NOT NULL CHECK (category IN (${list(EXPENSE_CATEGORIES)})),
  amount     INTEGER NOT NULL CHECK (amount >= 0),
  spent_on   TEXT NOT NULL,
  note       TEXT,
  created_at TEXT NOT NULL DEFAULT (${NOW})
);
CREATE INDEX IF NOT EXISTS idx_expenses_user ON expenses(user_id, spent_on);

-- What was harvested, and what it brought in when sold (income, whole shillings; 0 when kept for the home).
CREATE TABLE IF NOT EXISTS harvests (
  id           ${ID},
  user_id      ${REF} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plot_id      ${REF} REFERENCES plots(id) ON DELETE SET NULL,
  crop         TEXT NOT NULL,
  quantity     ${REAL} NOT NULL CHECK (quantity > 0),
  unit         TEXT NOT NULL,          -- kg, bags, crates, heads, bunches
  income       INTEGER NOT NULL DEFAULT 0 CHECK (income >= 0),
  harvested_on TEXT NOT NULL,
  note         TEXT,
  created_at   TEXT NOT NULL DEFAULT (${NOW})
);
CREATE INDEX IF NOT EXISTS idx_harvests_user ON harvests(user_id, harvested_on);

CREATE TABLE IF NOT EXISTS markets (
  id     ${ID},
  name   TEXT NOT NULL UNIQUE,
  county TEXT NOT NULL
);

-- Price per kg in shillings. 'sample' rows are the guide prices ShambaSmart starts with; 'farmer' rows are what
-- farmers saw or sold at, and replace the sample at that market once there are recent ones.
CREATE TABLE IF NOT EXISTS prices (
  id           ${ID},
  market_id    ${REF} NOT NULL REFERENCES markets(id),
  crop         TEXT NOT NULL,
  price_per_kg INTEGER NOT NULL CHECK (price_per_kg > 0),
  source       TEXT NOT NULL CHECK (source IN ('sample', 'farmer')),
  user_id      ${REF} REFERENCES users(id) ON DELETE SET NULL,
  observed_on  TEXT NOT NULL,
  created_at   TEXT NOT NULL DEFAULT (${NOW})
);
CREATE INDEX IF NOT EXISTS idx_prices_crop ON prices(crop, market_id, observed_on);

-- Photo checks. The photo itself is not kept, only what was found.
CREATE TABLE IF NOT EXISTS diagnoses (
  id         ${ID},
  user_id    ${REF} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plot_id    ${REF} REFERENCES plots(id) ON DELETE SET NULL,
  crop       TEXT,
  result     TEXT NOT NULL,           -- JSON (services/diagnose.js)
  created_at TEXT NOT NULL DEFAULT (${NOW})
);
CREATE INDEX IF NOT EXISTS idx_diagnoses_user ON diagnoses(user_id, created_at);
`;

/** The four query functions over one way of running SQL: `exec(sql, params)` gives { rows, changes, id }. */
function queries(exec) {
  return {
    one: async (sql, ...params) => (await exec(sql, params)).rows[0],
    all: async (sql, ...params) => (await exec(sql, params)).rows,
    run: async (sql, ...params) => ({ changes: (await exec(sql, params)).changes }),
    insert: async (sql, ...params) => (await exec(sql, params, true)).id,
  };
}

let backend;

// ---------- SQLite ----------
async function openSqlite() {
  const { DatabaseSync } = await import('node:sqlite');
  if (config.dbPath !== ':memory:') mkdirSync(dirname(config.dbPath), { recursive: true });
  const db = new DatabaseSync(config.dbPath);
  db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;');
  db.exec(SCHEMA);
  const exec = async (sql, params, inserting) => {
    const statement = db.prepare(sql);
    if (/^\s*select/i.test(sql)) return { rows: statement.all(...params) };
    const result = statement.run(...params);
    return { rows: [], changes: Number(result.changes), id: inserting ? Number(result.lastInsertRowid) : undefined };
  };
  // node:sqlite is synchronous, so one transaction at a time; a queue keeps two requests' transactions apart.
  let queue = Promise.resolve();
  const transaction = (fn) => {
    const next = queue.then(async () => {
      db.exec('BEGIN');
      try {
        const result = await fn(queries(exec));
        db.exec('COMMIT');
        return result;
      } catch (error) {
        db.exec('ROLLBACK');
        throw error;
      }
    });
    queue = next.catch(() => {});
    return next;
  };
  return { ...queries(exec), transaction, close: async () => db.close() };
}

// ---------- PostgreSQL ----------
// Test schemas are named ss_test_<random> so a test database shared with another project is never touched otherwise.
export const TEST_SCHEMA_PREFIX = 'ss_test_';

/** ? placeholders to $1, $2 ... (none of ShambaSmart's SQL has a ? inside quotes). */
const numbered = (sql) => {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
};

async function openPostgres() {
  const { default: pgLib } = await import('pg');
  // COUNT(*) comes back as bigint and SUM as numeric, which `pg` gives as text; ShambaSmart's are small numbers.
  pgLib.types.setTypeParser(pgLib.types.builtins.INT8, Number);
  pgLib.types.setTypeParser(pgLib.types.builtins.NUMERIC, Number);
  if (!config.databaseUrl) throw new Error('DB_ENGINE=postgres needs DATABASE_URL (the Neon connection string)');

  // Tests: each test file works in its own empty schema of the test database, removed by the test runner.
  const schema = config.dbIsolate ? `${TEST_SCHEMA_PREFIX}${randomBytes(6).toString('hex')}` : null;
  const pool = new pgLib.Pool({
    connectionString: config.databaseUrl,
    max: 5,
    allowExitOnIdle: true,
    ...(schema && { options: `-c search_path=${schema}` }),
  });
  if (schema) await pool.query(`CREATE SCHEMA ${schema}`);
  await pool.query(SCHEMA);

  const execOn = (client) => async (sql, params, inserting) => {
    const result = await client.query(numbered(inserting ? `${sql} RETURNING id` : sql), params);
    return { rows: result.rows, changes: result.rowCount ?? 0, id: inserting ? result.rows[0]?.id : undefined };
  };
  const transaction = async (fn) => {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await fn(queries(execOn(client)));
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally {
      client.release();
    }
  };
  return { ...queries(execOn(pool)), transaction, close: () => pool.end() };
}

/** Opens the database and makes the tables (safe to call again). */
export async function initDb() {
  backend ??= await (pg ? openPostgres() : openSqlite());
  return backend;
}

const ready = () => {
  if (!backend) throw new Error('initDb() has not been called');
  return backend;
};

export const one = (sql, ...params) => ready().one(sql, ...params);
export const all = (sql, ...params) => ready().all(sql, ...params);
export const run = (sql, ...params) => ready().run(sql, ...params);
export const insert = (sql, ...params) => ready().insert(sql, ...params);
export const transaction = (fn) => ready().transaction(fn);
export const closeDb = async () => {
  await backend?.close();
  backend = undefined;
};
